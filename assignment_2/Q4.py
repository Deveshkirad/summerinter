#Q4) Do practise of assignment operators

a = 14
b = 9
a += b
print(a)
a -= b     # a = a - b   a= 23 - 9 = 14
print(a)
a *= b      # a = a * b   a = 14 * 9 = 126
print(a)
a /= b      # a = a / b   a = 126 / 9 = 14.0
print(a)
a %= b      # a = a % b   a = 14.0 % 9 = 5.0
print(a)
a **= b     # a = a ** b   a = 5.0 ** 9 = 1953125.0
print(a)
a //= b     # a = a // b   a = 1953125.0 // 9 = 217013.0
print(a)